/* ============================================================================
   supabase/seed/br_municipalities.csv  →  supabase/seed/br_municipalities.sql

     node tools/gen-municipalities.mjs

   The CSV is the committed source (IBGE, servicodados.ibge.gov.br/api/v1/
   localidades/municipios, all 5,571 municipalities). The SQL is generated
   from it and is what setup.sql carries, so the city picker needs no
   network and no file upload on a fresh database. Idempotent: on conflict
   the row is refreshed, so a re-run after an IBGE update corrects names.

   search_key is the name lower-cased with its accents stripped, so
   "sao paulo" finds São Paulo without the unaccent extension.
   ============================================================================ */

import { readFileSync, writeFileSync } from 'node:fs'

const csv = readFileSync('supabase/seed/br_municipalities.csv', 'utf8').trim().split('\n')
const header = csv.shift()
if (header !== 'ibge_code,name,uf,region') throw new Error(`unexpected header: ${header}`)

/* RFC 4180, enough for this file: a field is quoted when it holds a comma. */
function parse(line) {
  const out = []
  let cur = ''
  let quoted = false
  for (let i = 0; i < line.length; i++) {
    const ch = line[i]
    if (quoted) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++ }
      else if (ch === '"') quoted = false
      else cur += ch
    } else if (ch === '"') quoted = true
    else if (ch === ',') { out.push(cur); cur = '' }
    else cur += ch
  }
  out.push(cur)
  return out
}

const sql = (s) => `'${s.replace(/'/g, "''")}'`
const key = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim()
const REGIONS = new Set(['N', 'NE', 'SE', 'S', 'CO'])

const rows = csv.map((line) => {
  const [code, name, uf, region] = parse(line)
  if (!/^\d{7}$/.test(code) || !/^[A-Z]{2}$/.test(uf) || !REGIONS.has(region) || !name) throw new Error(`bad row: ${line}`)
  return `(${sql(code)},${sql(name)},${sql(uf)},${sql(region)},${sql(key(name))})`
})

writeFileSync('supabase/seed/br_municipalities.sql', [
  '-- GENERATED by tools/gen-municipalities.mjs from supabase/seed/br_municipalities.csv',
  `-- ${rows.length} IBGE municipalities. Do not edit by hand: edit the CSV and regenerate.`,
  'insert into br_municipalities (ibge_code, name, uf, region, search_key) values',
  rows.join(',\n'),
  'on conflict (ibge_code) do update set name = excluded.name, uf = excluded.uf, region = excluded.region, search_key = excluded.search_key;',
  '',
].join('\n'))
console.log(`wrote supabase/seed/br_municipalities.sql (${rows.length} rows)`)
